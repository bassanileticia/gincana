    <h1>Gincana esportiva SENAI</h1>
    
    <p>A Gincana Esportiva do SENAI é um evento que reúne as turmas do <strong>9º Ano, 1º EM, 2º EM e 3º EM</strong> em uma competição cheia de trabalho em equipe e espírito esportivo.</p>

<p>Durante o evento, todas as turmas competem entre si em diferentes modalidades, sendo <strong>todos contra todos</strong>
</p>

<h2>Regras da Gincana</h2>

<ul>
    <li>Não existe empate: sempre há um vencedor.</li>
    <li>Cada vitória vale 1 ponto.</li>
    <li>Todas as turmas se enfrentam.</li>
    <li>A classificação é definida pelo total de pontos.</li>
</ul>

